#!/usr/bin/env python3
"""
Regenerate _catalogue.py from the BIMRACE service catalogue workbook.

    python generate_catalogue.py [path-to-xlsx]

The workbook is the source of truth for what each service page lists under
"Catalogue scope". This is the only script in _source that needs a third-party
package (openpyxl); build.py itself reads the generated _catalogue.py and stays
dependency-free.
"""
import ast
import pathlib
import pprint
import sys

import openpyxl

DEFAULT = pathlib.Path.home() / "Downloads" / "BIMRACE_Building_Sector_Service_Catalogue.xlsx"
OUT = pathlib.Path(__file__).resolve().parent / "_catalogue.py"


def main():
    src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
    ws = openpyxl.load_workbook(src, data_only=True)["Service Catalogue"]
    items = []
    for row in ws.iter_rows(min_row=2, values_only=True):
        category, code, name, output, discipline, phase, note = (tuple(row) + (None,) * 7)[:7]
        if not code:
            continue
        name = str(name).strip()
        # Some rows hold "('Service name', 'Specific output')" in the name column.
        if name.startswith("("):
            name, output = ast.literal_eval(name)
        items.append({
            "code": str(code).strip(),
            "category": str(category).strip(),
            "name": name,
            "output": str(output or "").strip(),
            "phase": str(phase or "").strip(),
            "note": str(note or "").strip(),
            # Calculations and sizing are offered only where design responsibility is agreed.
            "design_scope": any(w in f"{name} {output}".lower() for w in ("calculation", "sizing")),
        })
    wb = ws.parent

    def rows(sheet, keys):
        out = []
        for r in wb[sheet].iter_rows(min_row=2, values_only=True):
            if r and r[0]:
                out.append({k: str(v or "").strip() for k, v in zip(keys, r)})
        return out

    packages = rows("Service Packages", ["code", "name", "included", "outputs", "qualification"])
    handover = rows("Handover Checklist", ["no", "deliverable", "description", "inclusion", "definition"])
    for h in handover:                      # Excel stores 01..10 as numbers
        h["no"] = h["no"].zfill(2)

    fmt = lambda v: pprint.pformat(v, width=100, sort_dicts=False)
    OUT.write_text(
        '"""AUTO-GENERATED by generate_catalogue.py from the BIMRACE service catalogue.\n'
        'Do not edit by hand: change the workbook and regenerate."""\n\n'
        f"CATALOGUE = {fmt(items)}\n\nPACKAGES = {fmt(packages)}\n\nHANDOVER = {fmt(handover)}\n",
        encoding="utf-8")
    print(f"wrote {len(items)} catalogue items, {len(packages)} packages, "
          f"{len(handover)} handover deliverables to {OUT.name}")


if __name__ == "__main__":
    main()
